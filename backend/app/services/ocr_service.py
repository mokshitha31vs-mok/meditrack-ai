import os
from app.services.image_service import preprocess_image_variants, validate_image_file

# Module-level singleton to avoid reloading PyTorch model weights on every request
_EASYOCR_READER = None

def get_easyocr_reader():
    global _EASYOCR_READER
    if _EASYOCR_READER is None:
        try:
            import easyocr
            # Initialize English reader on CPU
            _EASYOCR_READER = easyocr.Reader(['en'], gpu=False, verbose=False)
        except Exception as e:
            print(f"[OCR Service] EasyOCR initialization notice: {e}")
            _EASYOCR_READER = False
    return _EASYOCR_READER if _EASYOCR_READER is not False else None


def perform_ocr(image_path):
    """
    Perform REAL Optical Character Recognition (OCR) on an uploaded prescription image.
    Evaluates image variants generated by OpenCV preprocessing pipeline.

    Order of preference:
    1. EasyOCR (with word/line confidence scores and bounding boxes)
    2. PyTesseract (if tesseract binary is installed and configured)

    Returns tuple:
      (raw_extracted_text, engine_used, confidence_percentage, detailed_line_items)

    STRICT SAFETY RULE:
    Never return hardcoded sample medicines if OCR fails. Return honest empty results
    so the patient is prompted for manual entry or image re-upload.
    """
    valid, err_msg = validate_image_file(image_path)
    if not valid:
        return "", f"Validation Error: {err_msg}", 0.0, []

    try:
        variant_paths = preprocess_image_variants(image_path)
    except Exception as e:
        return "", f"Preprocessing Error: {str(e)}", 0.0, []

    best_text = ""
    best_conf = 0.0
    best_line_items = []
    engine_name = "EasyOCR"

    # Attempt 1: EasyOCR with cached reader
    reader = get_easyocr_reader()
    if reader is not None:
        try:
            for v_idx, path in enumerate(variant_paths):
                if not os.path.exists(path):
                    continue
                # detail=1 returns list of (bbox, text, prob)
                # min_size=5, text_threshold=0.35, low_text=0.25, width_ths=0.6 preserve small duration digits and table columns
                results = reader.readtext(path, detail=1, min_size=5, text_threshold=0.35, low_text=0.25, width_ths=0.6)
                if not results:
                    continue

                line_items = []
                for res in results:
                    text_str = str(res[1]).strip()
                    prob = float(res[2])
                    raw_bbox = res[0]  # [[x1,y1], [x2,y1], [x2,y2], [x1,y2]]
                    if text_str:
                        # Convert all coordinates to native Python ints to prevent int32 JSON serialization error
                        clean_bbox = [[int(pt[0]), int(pt[1])] for pt in raw_bbox]
                        y_center = float((raw_bbox[0][1] + raw_bbox[2][1]) / 2.0)
                        x_left = float(raw_bbox[0][0])
                        line_items.append({
                            'text': text_str,
                            'confidence': round(float(prob) * 100.0, 1),
                            'bbox': clean_bbox,
                            'y': round(y_center, 2),
                            'x': round(x_left, 2)
                        })

                if line_items:
                    # Sort items top-to-bottom
                    line_items.sort(key=lambda item: item['y'])

                    # Cluster tokens horizontally into lines based on vertical proximity (16px)
                    clustered_lines = []
                    current_line_tokens = []
                    current_y_avg = None

                    for item in line_items:
                        if current_y_avg is None or abs(item['y'] - current_y_avg) <= 16:
                            current_line_tokens.append(item)
                            current_y_avg = sum(tok['y'] for tok in current_line_tokens) / len(current_line_tokens)
                        else:
                            current_line_tokens.sort(key=lambda tok: tok['x'])
                            clustered_lines.append(" ".join(tok['text'] for tok in current_line_tokens))
                            current_line_tokens = [item]
                            current_y_avg = item['y']

                    if current_line_tokens:
                        current_line_tokens.sort(key=lambda tok: tok['x'])
                        clustered_lines.append(" ".join(tok['text'] for tok in current_line_tokens))

                    combined_text = "\n".join(clustered_lines)
                    avg_conf = float(sum(item['confidence'] for item in line_items) / len(line_items))

                    if len(combined_text) > len(best_text) or (len(combined_text) > 20 and avg_conf > best_conf):
                        best_text = combined_text
                        best_conf = avg_conf
                        best_line_items = line_items

                    # If primary enhanced variant achieved good read, exit loop early to save compute
                    if v_idx <= 1 and len(clustered_lines) >= 4 and avg_conf >= 60.0:
                        break

            if best_text.strip():
                return best_text.strip(), f"EasyOCR (Confidence: {round(best_conf, 1)}%)", round(best_conf, 1), best_line_items

        except Exception as e:
            print(f"[OCR Service] EasyOCR execution notice: {e}")

    # Attempt 2: PyTesseract fallback
    try:
        import pytesseract
        from PIL import Image

        best_tess_text = ""
        for path in variant_paths:
            if not os.path.exists(path):
                continue
            img = Image.open(path)
            text = pytesseract.image_to_string(img)
            if len(text.strip()) > len(best_tess_text):
                best_tess_text = text.strip()

        if best_tess_text:
            lines = [l.strip() for l in best_tess_text.split('\n') if l.strip()]
            tess_items = [{'text': l, 'confidence': 75.0, 'bbox': [], 'y': idx * 20.0, 'x': 0.0} for idx, l in enumerate(lines)]
            return best_tess_text, "Tesseract OCR Engine", 75.0, tess_items

    except Exception as e:
        print(f"[OCR Service] PyTesseract notice: {e}")

    # If neither OCR engine succeeded in reading text from the image
    return "", "No OCR Text Detected", 0.0, []
